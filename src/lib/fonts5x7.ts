export function textToData(text: string, level = 4): number[][] | null {
  const chars = text.toUpperCase().split("")
  const colWidth = 6 // 5 + 1 gap
  const totalCols = chars.length * colWidth - 1
  if (totalCols <= 0) return null
  // return as cols x rows (7)
  const cols: number[][] = Array.from({ length: totalCols }, () => Array(7).fill(-1))
  chars.forEach((ch, idx) => {
    const glyph = FONT_5x7[ch] ?? FONT_5x7[" "]
    const offset = idx * colWidth
    for (let y = 0; y < 7; y++) {
      for (let x = 0; x < 5; x++) {
        if (glyph[y][x]) cols[offset + x][y] = level
        else cols[offset + x][y] = 0
      }
    }
  })
  return cols
}
